/**
 * npm run db:register
 *
 * Tables created by hand-written SQL migrations (0004+: roles, purchases, service, HR ...)
 * have no Mongoose model, so `npm run db:generate` cannot see them. This reads their layout
 * from the migrated database and adds them to
 *   - src/database/pg/registry.generated.ts   (tagged managedBy: "sql")
 *   - src/database/drizzle/schema.generated.ts
 * so `npm run db:verify` and the typed Drizzle view cover them. It also adds columns that a
 * migration added to an already-registered table (e.g. lead_users.role_id). Nothing in the
 * database changes; registry entries are only added, never removed or retyped.
 *
 * Run order after a new SQL migration: db:migrate -> db:generate -> db:register -> db:verify
 */
const fs = require("fs");
const path = require("path");
const { BACKEND_DIR, registerTypeScript, connect, redact } = require("./lib");

process.chdir(BACKEND_DIR);
registerTypeScript();
const { REGISTRY } = require(path.join(BACKEND_DIR, "src/database/pg/registry.generated.ts"));

const camel = (s) => s.replace(/_+([a-z0-9])/g, (_, c) => c.toUpperCase());
const KIND = { text: "string", "double precision": "number", "timestamp with time zone": "date", boolean: "boolean", jsonb: "json", "text[]": "string[]" };

(async () => {
  const schema = Object.values(REGISTRY.databases)[0];
  const database = Object.keys(REGISTRY.databases)[0];
  const c = await connect("movement-tracking-db-register");
  let rows;
  try {
    rows = (
      await c.query(
        `SELECT c.relname t, a.attname col, format_type(a.atttypid, a.atttypmod) typ, a.attnum
           FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid AND c.relkind = 'r'
           JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE n.nspname = $1 AND a.attnum > 0 AND NOT a.attisdropped
          ORDER BY c.relname, a.attnum`,
        [schema],
      )
    ).rows;
  } finally {
    await c.end();
  }
  const byTable = new Map();
  for (const r of rows) {
    if (!byTable.has(r.t)) byTable.set(r.t, []);
    byTable.get(r.t).push(r);
  }
  const tables = REGISTRY.tables.map((t) => ({ ...t, columns: [...t.columns] }));
  const known = new Map(tables.map((t) => [t.table, t]));
  const problems = [];
  const summary = [];
  const columnsFor = (rowsOfTable, have) => {
    const out = [];
    for (const r of rowsOfTable) {
      if (["id", "_nulls", "_extra"].includes(r.col) || have.has(r.col)) continue;
      const kind = KIND[r.typ.replace(' COLLATE "C"', "")];
      if (!kind) {
        problems.push(`${r.t}.${r.col}: unsupported type ${r.typ}`);
        continue;
      }
      out.push({ field: camel(r.col), column: r.col, kind });
    }
    return out;
  };
  for (const [name, cols] of [...byTable].sort()) {
    const existing = known.get(name);
    if (existing) {
      const add = columnsFor(cols, new Set(existing.columns.map((x) => x.column)));
      if (add.length) {
        existing.columns.push(...add);
        summary.push(`${name}: +${add.length} column(s) (${add.map((x) => x.column).join(", ")})`);
      }
      continue;
    }
    if (name === "schema_migrations") continue;
    const columns = columnsFor(cols, new Set());
    tables.push({ database, collection: name, schema, table: name, idKind: "objectId", managedBy: "sql", columns, indexes: [] });
    summary.push(`new ${schema}.${name} (${columns.length} columns)`);
  }
  if (problems.length) throw new Error(`cannot register:\n${problems.join("\n")}`);
  if (!summary.length) return console.log("Registry already covers every table in the database.");
  const registry = { ...REGISTRY, tables };
  fs.writeFileSync(
    path.join(BACKEND_DIR, "src/database/pg/registry.generated.ts"),
    "/* eslint-disable */\n// GENERATED by database/generate.js — do not edit by hand.\n" + 'import type { Registry } from "./registry";\n\n' + `export const REGISTRY: Registry = ${JSON.stringify(registry, null, 1)};\n`,
  );
  require("./drizzle").writeDrizzle(registry);
  console.log(summary.join("\n"));
  console.log("registry.generated.ts and schema.generated.ts rewritten. Next: npm run db:verify");
})().catch((e) => {
  console.error("FAILED:", redact(e && e.message ? e.message : e));
  process.exit(1);
});
